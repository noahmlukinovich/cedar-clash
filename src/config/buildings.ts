export function maxLevelForDmc(type: BuildingType, dmc: number): number {
  const def = BUILDINGS[type];
  let m = 0;
  def.levels.forEach((l, i) => {
    if (l.dmc <= dmc) m = i + 1;
  });
  return m;
}

export function maxCount(type: BuildingType, dmc: number): number {
  const c = BUILDINGS[type].counts;
  return c[Math.min(dmc, c.length - 1)] ?? 0;
}

export function blocksPath(type: BuildingType): boolean {
  return BUILDINGS[type].blocksPath !== false;
}
