function tl(hp: number[], dps: number[], cost: number[], rcost: number[], rtime: number[], lib: number[]): TroopLevel[] {
  return hp.map((h, i) => ({
    hp: h,
    dps: dps[i],
    cost: cost[i],
    researchCost: rcost[i],
    researchTime: rtime[i],
    libraryLevel: lib[i],
  }));
}

